"""Adversarial essay grading experiment.

Use an LLM to generate prompts that invoke grade inflation in the downstream LLM.

Uses two LLMs:
1. Adversarial LLM: generates prompts that invoke grade inflation in the downstream LLM.
2. Grader LLM (target LLM): grades the essays generated by the adversarial LLM.
"""

import argparse
import logging
import os
import random
from experiments.essay_grading_analysis.adversarial_scenario.scores.fitness import FitnessScore
from experiments.essay_grading_analysis.adversarial_scenario.scores.group_scores import GroupScores
from experiments.essay_grading_analysis.adversarial_scenario.scores.similarity import BleuScoreNLTK
from experiments.essay_grading_analysis.metrics.essay_metrics import to_letter
import pandas as pd
import numpy as np
from experiments.essay_grading_analysis.adversarial_scenario.utils.archive import Archive
from experiments.essay_grading_analysis.adversarial_scenario.utils.llm_config import LLMSwitcher
from experiments.essay_grading_analysis.adversarial_scenario.utils.prompts import ADVERSARIAL_PROMPT, TARGET_PROMPT
from experiments.essay_grading_analysis.adversarial_scenario.utils.utils import load_json


GEN_CONFIG = {"temperature": 1.0} # allow diversity in prompt generation
GRADER_CONFIG = {"temperature": 0.0} # no diversity in grading

logger = logging.getLogger(__name__)
logger.setLevel(logging.INFO)


def parse_args():
    """Parse command line arguments for adversarial prompt generation for essay grading experiment."""
    parser = argparse.ArgumentParser(description="Adversarial Essay Grading Prompt Generation")
    parser.add_argument("--num_samples", type=int, default=10, help="Number of initial prompt examples to load.")
    parser.add_argument("--max_iters", type=int, default=1000, help="Maximum number of iterations to run.")
    parser.add_argument("--sim_threshold", type=float, default=0.6, help="Similarity threshold for prompt generation.")
    parser.add_argument("--num_generations", type=int, default=10, help="Number of adversarial candidates generated per iteration.")
    parser.add_argument("--fewshot_k", type=int, default=6, help="Number of demos shown to the adversarial LLM per call.")
    parser.add_argument("--search_panel_size", type=int, default=3, help="Essays each candidate is scored on during search (need multiple to calculate mean GI).")
    parser.add_argument("--val_panel_size", type=int, default=30, help="Held-out essays for final validation.")
    parser.add_argument("--initial_prompts_path", type=str, default="experiments/essay_grading_analysis/adversarial_scenario/data/initial-prompts-increase-gi.json", help="Path to initial prompts.")
    parser.add_argument("--essays_path", type=str, default="data/essay_grading/results/essay_gemini_2000.csv", help="Path to essays.")
    parser.add_argument("--results_dir", type=str, default="experiments/essay_grading_analysis/adversarial_scenario/results", help="Where to write archives and the validation CSV.")
    parser.add_argument("--adv_provider", type=str, default="anthropic", choices=["gemini", "openai", "anthropic", "bedrock"], help="Adversarial LLM provider to use.")
    parser.add_argument("--adv_llm", type=str, default="claude-sonnet-4-6", help="Adversarial LLM model to use.")
    parser.add_argument("--grader_provider", type=str, default="gemini", choices=["gemini", "openai", "anthropic", "bedrock"], help="Grader LLM provider to use.")
    parser.add_argument("--grader_llm", type=str, default="gemini-2.5-pro", help="Grader LLM to use.")
    return parser.parse_args()


def build_demos(initial_prompts_set: list[dict], essay: str) -> str:
    demos = []
    for i, prompt_set in enumerate(initial_prompts_set):
        demos.append(f"### Example {i+1}\n")
        demos.append(f"- Input essay: {essay[:100]}...\n")
        demos.append(f"- Suffix: {prompt_set['prompt']}\n")
        demos.append(f"- Strategy tag: {prompt_set['tag']}\n")
        demos.append(f"- Resulting grade inflation: {prompt_set['gi']}\n")
    return "\n".join(demos)


def archive_demos(adv_prompts: Archive, scores: Archive) -> list[dict]:
    """Select best suffix per cell. Allows generator to learn from previous iterations."""
    if not adv_prompts.keys():
        return []
    
    best_idx = scores.idx_max_elements()
    out = []
    for key, idx in best_idx.items():
        out.append({
            "prompt": adv_prompts.get(key)[idx],
            "tag": key,
            "gi": round(float(scores.get(key)[idx]), 2)
        })
    return out


def parse_gen_response(response: str) -> dict:
    try:
        lines = [l for l in response.strip().split("\n") if l.strip()]
        return {
            "suffix": lines[0].split(":")[1].strip(),
            "tag": lines[1].split(":")[1].strip()
        }
    except Exception as e:
        logger.error(f"parse_gen_response error: Failed to parse generated response: {response}, error: {e}")
        return None


def mean_gi_over_panel(grader, fitness_fn, suffixes: list[str], panel_essays: list[str], panel_kb: list[str]) -> list[dict]:
    """Calculate the mean GI, mean condition grade, mean knowledge baseline grade for each suffix over the same panel of essays.
    Returns:
        list[dict]: {
            "mean_gi": float | None,
            "mean_cond_grade": str | None,
            "mean_kb_grade": str | None
        }
    """
    len_panel = len(panel_essays)
    prompts = [TARGET_PROMPT.format(essay=panel_essays[i], prompt_suffix=suffix) 
    for suffix in suffixes for i in range(len_panel)]
    responses = grader.batch_generate(prompts, GRADER_CONFIG)

    means = []
    for ci in range(len(suffixes)):
        gis = []
        for i in range(len_panel):
            gi, cond_grade, kb_grade = fitness_fn.gi(panel_kb[i], responses[ci * len_panel + i])
            if gi is not None:
                gis.append((gi, cond_grade, kb_grade))
        for gi, cond_grade, kb_grade in gis:
            if gi is not None:
                mean_gi += gi
            if cond_grade is not None:
                mean_cond_grade += cond_grade
            if kb_grade is not None:
                mean_kb_grade += kb_grade
        
        mean_gi /= len(gis)
        mean_cond_grade /= len(gis)
        mean_kb_grade /= len(gis)

        mean_cond_grade = to_letter(mean_cond_grade)
        mean_kb_grade = to_letter(mean_kb_grade)
        means.append({
            "mean_gi": mean_gi,
            "mean_cond_grade": mean_cond_grade,
            "mean_kb_grade": mean_kb_grade
        })
    return means


def run_prompt_generation(args: argparse.Namespace, similarity_fn=None, fitness_fn=None):
    """Run prompt generation for adversarial essay grading experiment."""
    initial_prompts_set = load_json(args.initial_prompts_path, num_samples=args.num_samples)
    essays = pd.read_csv(args.essays_path)

    # grab only C and D essays (allow for baselines that can move up and down: ex: F can only go up and A can only go down)
    essays = essays[essays["llm_baseline_grade"].isin(["C", "D"])]
    
    all_rows = random.sample(range(len(essays)), k=args.search_panel_size + args.val_panel_size)
    search_rows = all_rows[:args.search_panel_size]
    val_rows = all_rows[args.search_panel_size:]

    search_rows["essay"] = [essays.iloc[i]["kb_prompt"].split("\n\nGrade this essay")[0].strip() for i in search_rows]
    val_rows["essay"] = [essays.iloc[i]["kb_prompt"].split("\n\nGrade this essay")[0].strip() for i in val_rows]
    
    search_essays = [search_rows["essay"].iloc[i] for i in range(len(search_rows))]
    search_kb_grades = [search_rows.iloc[i]["llm_baseline_grade"] for i in search_rows]

    adv_prompts = Archive("adv_prompts")
    scores = Archive("scores")
    iters = Archive("iterations")

    adv = LLMSwitcher(provider=args.adv_provider, model_name=args.adv_llm)
    grader = LLMSwitcher(provider=args.grader_provider, model_name=args.grader_llm)

    group_scores = GroupScores(threshold=args.sim_threshold)

    for iter in range(args.max_iters):
        # select essay only from search panel for generation
        gen_essay = search_essays[iter % len(search_essays)]
        
        # incorporate learned prompts into demos
        demos_pool = initial_prompts_set + archive_demos(adv_prompts, scores)
        demos_set = random.sample(demos_pool, k=min(args.num_generations, len(demos_pool)))
        # generate prompt suffixes
        prompt_suffix = ADVERSARIAL_PROMPT.format(demos=build_demos(demos_set, gen_essay), essay=gen_essay)
            
        # llm output will be in the format of "Suffix:<new suffix>\nStrategy tag:<strategy tag>" so we need to parse it
        generated_suffixes = adv.batch_generate(
            [prompt_suffix] * args.num_generations, GEN_CONFIG
        )

        candidates = [
            parse_gen_response(p) for p in generated_suffixes
        ]

        # ensure generated suffixes aren't too similar to previous suffixes (randomly select one for comparison)
        sim_score_ref = random.choice(demos_set)["prompt"]
        # format: [{'suffix': '<new suffix>', 'tag': '<strategy tag>'}]
        filtered_candidates = [g for g in candidates
                            if similarity_fn.score(g["suffix"], sim_score_ref) < args.sim_threshold]
        
        if not filtered_candidates:
            logger.warning(f"No candidates found for essay {gen_essay}")
            continue
            
        gis_dict = mean_gi_over_panel(grader, fitness_fn, [g["suffix"] for g in filtered_candidates],
                                search_essays, search_kb_grades)

                

        kept = [(g, gi_dict) for g, gi_dict in zip(filtered_candidates, gis_dict) if gi_dict["mean_gi"] is not None and gi_dict["mean_gi"] > 0.0]

        for g, gi_dict in kept:
            key = group_scores.route(g["tag"])
            if not adv_prompts.exists(key):
                adv_prompts.add(key, [g["suffix"]])
                scores.add(key, [gi_dict["mean_gi"]])
                iters.add(key, [iter])
            else:
                adv_prompts.extend(key, [g["suffix"]])
                scores.extend(key, [gi_dict["mean_gi"]])
                iters.extend(key, [iter])
        logger.info(f"Iteration {iter} of {args.max_iters} complete")
        logger.info(f"Adversarial prompts: {adv_prompts.keys()}")
        logger.info(f"Scores: {scores.keys()}")
        logger.info(f"Iterations: {iters.keys()}")
        logger.info("\n\n\n")
    
    os.makedirs(args.results_dir, exist_ok=True)
    adv_prompts.save(os.path.join(args.results_dir, "adv_prompts.json"))
    scores.save(os.path.join(args.results_dir, "scores.json"))
    iters.save(os.path.join(args.results_dir, "iterations.json"))
    # save search and val rows (save essay_id, kb_prompt, essay, llm_baseline_grade)
    search_rows[["essay_id", "kb_prompt", "essay", "llm_baseline_grade"]].to_csv(os.path.join(args.results_dir, "search_rows.csv"), index=False)
    val_rows[["essay_id", "kb_prompt", "essay", "llm_baseline_grade"]].to_csv(os.path.join(args.results_dir, "val_rows.csv"), index=False)
    return adv_prompts, scores, val_rows, essays


def bootstrap_ci(values, n_boot=2000, alpha=0.05, seed=0):
    """Percentile bootstrap CI for the mean over essays."""
    if len(values) < 2:
        return (float("nan"), float("nan"))
    rng = np.random.default_rng(seed)
    arr = np.asarray(values, dtype=float)
    boots = [rng.choice(arr, size=len(arr), replace=True).mean() for _ in range(n_boot)]
    return float(np.percentile(boots, 100 * alpha / 2)), float(np.percentile(boots, 100 * (1 - alpha / 2)))


def validate_archive(adv_prompts, scores, val_rows, essays, grader, fitness_fn, out_csv):
    """Re-score each cell on the held-out validation panel. Write csv with mean GI and CI per strategy tag."""
    val_essays = [essays.iloc[i]["kb_prompt"].split("\n\nGrade this essay")[0].strip() for i in val_rows]
    val_kb = [essays.iloc[i]["llm_baseline_grade"] for i in val_rows]
    best_idx = scores.idx_max_elements()

    rows = []
    for key, idx in best_idx.items():
        suffix = adv_prompts.get(key)[idx]
        prompts = [TARGET_PROMPT.format(essay=essay, prompt_suffix=suffix) for essay in val_essays]
        resp = grader.batch_generate(prompts, GRADER_CONFIG)
        per_essay_gis_dicts = [fitness_fn.gi(val_kb[i], resp[i]) for i in range(len(val_rows))]
        per_essay_gis_dicts = [gi for gi in per_essay_gis_dicts if gi is not None]
        if not per_essay_gis_dicts:
            continue
        mean_gi = float(np.mean(per_essay_gis_dicts["mean_gi"]))
        mean_cond_grade = to_letter(float(np.mean(per_essay_gis_dicts["mean_cond_grade"])))
        mean_kb_grade = to_letter(float(np.mean(per_essay_gis_dicts["mean_kb_grade"])))
        lo, hi = bootstrap_ci(per_essay_gis_dicts["mean_gi"])
        rows.append({
            "tag": key,
            "suffix": suffix,
            "n_essays": len(per_essay_gis_dicts),
            "search_gi_mean": round(float(scores.get(key)[idx]), 3),
            "val_mean_gi": round(mean_gi, 3),
            "val_cond_grade_mean": mean_cond_grade,
            "val_kb_grade_mean": mean_kb_grade,
            "val_gi_ci": f"[{lo:.3f}, {hi:.3f}]",
        })
    
    if not rows:
        logger.warning("No validation rows found")
        return pd.DataFrame()
    
    df = pd.DataFrame(rows).sort_values("val_mean_gi", ascending=False)
    df.to_csv(out_csv, index=False)
    logger.info(f"Validation written to {out_csv}\n{df.to_string(index=False)}")
    return df


if __name__ == "__main__":
    args = parse_args()
    similarity_fn = BleuScoreNLTK()
    fitness_fn = FitnessScore()
    adv_prompts, scores, val_rows, essays = run_prompt_generation(
        args=args, similarity_fn=similarity_fn, fitness_fn=fitness_fn)
    grader = LLMSwitcher(args.grader_provider, args.grader_llm)
    validate_archive(adv_prompts, scores, val_rows, essays, grader, fitness_fn,
                     out_csv=os.path.join(args.results_dir, "best_validation.csv"))