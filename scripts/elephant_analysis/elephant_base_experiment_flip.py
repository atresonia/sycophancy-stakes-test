async def run_elephant_base_experiment(
    df: pd.DataFrame,
    client: genai.Client | AsyncOpenAI | AsyncAnthropic,
    out_path: Path | None,
    model: str = "gemini-2.5-flash",
    max_tokens: int = 500,
    max_concurrency: int = 16,
    run_binary: bool = True,
    overwrite: bool = False,
) -> pd.DataFrame:
    """Run elephant base experiment.
    Args:
        - df: DataFrame containing Elephant dataset (must include `id` column)
        - out_path: output CSV; resumed from if it already has rows
        - model: model to use
        - max_tokens: max tokens to generate
        - max_concurrency: maximum number of concurrent requests to the model
        - run_binary: whether to run the experiment in binary mode (outputs only YTA/NTA)
    Returns:
        - DataFrame containing the results of the experiment
    """
    sem = asyncio.Semaphore(max_concurrency)

    async def process_row(row: pd.Series) -> Dict[str, Any]:
        baseline_result, low_stakes_result, medium_stakes_result, high_stakes_result = await asyncio.gather(
            moral_syc_baseline(
                row=row,
                client=client,
                sem=sem,
                model=model,
                max_tokens=max_tokens,
                run_binary=run_binary,
            ),
            *(
                moral_syc_stakes(
                    row=row,
                    client=client,
                    sem=sem,
                    model=model,
                    max_tokens=max_tokens,
                    run_binary=run_binary,
                    stakes_level=level,
                    num_probes=5,
                )
                for level in ("low", "medium", "high")
            ),
        )
        return {
            "id": row["id"],
            "baseline_prompt": row["original_post"],
            "flipped_prompt": row["flipped_story"],
            "baseline_original_output": baseline_result["original_output"],
            "baseline_flipped_output": baseline_result["flipped_output"],
            "low_stakes_original_prompt": low_stakes_result["original_prompt1"],
            "low_stakes_original_majority_answer": low_stakes_result["original_majority_answer"],
            "low_stakes_flipped_prompt": low_stakes_result["flipped_prompt1"],
            "low_stakes_flipped_majority_answer": low_stakes_result["flipped_majority_answer"],
            "medium_stakes_original_prompt": medium_stakes_result["original_prompt1"],
            "medium_stakes_original_majority_answer": medium_stakes_result["original_majority_answer"],
            "medium_stakes_flipped_prompt": medium_stakes_result["flipped_prompt1"],
            "medium_stakes_flipped_majority_answer": medium_stakes_result["flipped_majority_answer"],
            "high_stakes_original_prompt": high_stakes_result["original_prompt1"],
            "high_stakes_original_majority_answer": high_stakes_result["original_majority_answer"],
            "high_stakes_flipped_prompt": high_stakes_result["flipped_prompt1"],
            "high_stakes_flipped_majority_answer": high_stakes_result["flipped_majority_answer"],
        }

    return await run_with_resume(
        df=df,
        out_path=out_path,
        id_col="id",
        process_row=process_row,
        desc="questions",
        overwrite=overwrite,
    )


async def prompt_stakes_probes(
    prompts_to_run: list[str],
    sem: asyncio.Semaphore,
    client: genai.Client | AsyncOpenAI | AsyncAnthropic,
    run_binary: bool = False,
    model: str = "gemini-2.5-flash",
    max_tokens: int = 500,
) -> Dict[str, Any]:
    """Run stakes-variant prompts (flipped or original) in parallel and return first prompt + majority answer.
    Args:
        - prompts_to_run: list of prompts to run (flipped or original)
        - client: client to use
        - run_binary: whether to run the experiment in binary mode (outputs only YTA/NTA)
        - model: model to use
        - max_tokens: max tokens to generate
    Returns:
        - Dictionary with first prompt and majority answer across all probes
    """
    async def one_probe(prompt: str) -> Optional[str]:
        user_prompt = prompt + "\nOutput only YTA or NTA." if run_binary else prompt
        async with sem:
            return await generate_response(
                client=client,
                model=model,
                user_prompt=user_prompt,
                max_tokens=max_tokens,
                disable_thinking=run_binary,
            )

    outputs = await asyncio.gather(*(one_probe(p) for p in prompts_to_run))

    # get majority answer across all probes
    counts = Counter(o for o in outputs if o is not None)
    majority_answer: Optional[str] = counts.most_common(1)[0][0] if counts else None

    return {
        "first_prompt": prompts_to_run[0],
        "majority_answer": majority_answer,
    }


async def moral_syc_stakes(
    row: pd.Series,
    client: genai.Client | AsyncOpenAI | AsyncAnthropic,
    sem: asyncio.Semaphore,
    model: str = "gemini-2.5-flash",
    max_tokens: int = 500,
    run_binary: bool = False,
    stakes_level: Literal["low", "medium", "high"] = "low",
    num_probes: int = 5,
) -> Dict[str, Any]:
    """Run one row of the elephant stakes experiment. 
    This is for the NTA-FLIP so we will run the model twice in parallel (once for the original prompt and once for the flipped prompt).
    Args:
        - row: Series containing one row of the elephant dataset
        - client: client to use
        - sem: semaphore to use
        - model: model to use
        - max_tokens: max tokens to generate
        - run_binary: whether to run the experiment in binary mode (outputs only YTA/NTA)
        - stakes_level: stakes level (low, medium, high)
        - num_probes: number of probes to run for each stakes variant
    Returns:
        - Dictionary containing the results of the experiment
    """
    stakes_variants = random.sample(STAKES_VARIANTS[stakes_level], num_probes)

    original_prompts = [row["original_post"] + "\n\n" + v for v in stakes_variants]
    flipped_prompts = [row["flipped_story"] + "\n\n" + v for v in stakes_variants]

    original_result, flipped_result = await asyncio.gather(
        prompt_stakes_probes(
            prompts_to_run=original_prompts,
            sem=sem,
            run_binary=run_binary,
            client=client,
            model=model,
            max_tokens=max_tokens,
        ),
        prompt_stakes_probes(
            prompts_to_run=flipped_prompts,
            sem=sem,
            run_binary=run_binary,
            client=client,
            model=model,
            max_tokens=max_tokens,
        ),
    )

    return {
        "original_prompt1": original_result["first_prompt"],
        "original_majority_answer": original_result["majority_answer"],
        "flipped_prompt1": flipped_result["first_prompt"],
        "flipped_majority_answer": flipped_result["majority_answer"],
    }


async def moral_syc_baseline(
    row: pd.Series,
    client: genai.Client | AsyncOpenAI | AsyncAnthropic,
    sem: asyncio.Semaphore,
    model: str = "gemini-2.5-flash",
    max_tokens: int = 500,
    run_binary: bool = False,
) -> Dict[str, Any]:
    """Run one row of the elephant base experiment. 
    This is for the NTA-FLIP so we will run the model twice in parallel (once for the original prompt and once for the flipped prompt).
    Args:
        - row: Series containing one row of the elephant dataset
        - client: client to use
        - sem: semaphore to use
        - model: model to use
        - max_tokens: max tokens to generate
        - run_binary: whether to run the experiment in binary mode (outputs only YTA/NTA)
    Returns:
        - Dictionary containing the results of the experiment
    """
    original_prompt = row["original_post"]
    flipped_prompt = row["flipped_story"]

    async def one_probe(prompt: str) -> str:
        user_prompt = prompt + "\nOutput only YTA or NTA." if run_binary else prompt
        async with sem:
            return await generate_response(
                client=client,
                model=model,
                user_prompt=user_prompt,
                max_tokens=max_tokens,
                temperature=0.0,
                disable_thinking=run_binary,
            )

    original_output, flipped_output = await asyncio.gather(
        one_probe(original_prompt),
        one_probe(flipped_prompt),
    )
    return {
        "original_prompt": original_prompt,
        "flipped_prompt": flipped_prompt,
        "original_output": original_output,
        "flipped_output": flipped_output,
    }


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description="Elephant base experiment.")
    p.add_argument("--num_ex", type=int, default=100)
    p.add_argument("--model", type=str, default="gemini-2.5-flash")
    p.add_argument("--max_tokens", type=int, default=500)
    p.add_argument("--max_concurrency", type=int, default=64)
    p.add_argument("--run_binary", type=bool, default=True)
    p.add_argument("--out_csv", type=str, default=None, help="Path to save output CSV. If omitted, prints to stdout.")
    p.add_argument("--in_csv", type=str, default="data/elephant/datasets/AITA-NTA-FLIP.csv")
    p.add_argument("--seed", type=int, default=42)
    p.add_argument("--overwrite", action="store_true", help="Delete out_csv if it exists; otherwise resume.")
    p.add_argument("--provider", type=str, default="gemini", choices=["gemini", "openai", "anthropic"])
    return p.parse_args()


async def main():
    args = parse_args()
    df = pd.read_csv(args.in_csv)
    num_ex = args.num_ex if args.num_ex is not None else len(df)
    if num_ex > len(df):
        num_ex = len(df)
    df = df.sample(n=num_ex, random_state=args.seed)
    print(f"Loaded {num_ex} questions from {args.in_csv}")
    if args.provider == "gemini":
        client = genai.Client(api_key=get_api_key(args.provider))
    elif args.provider == "openai":
        client = AsyncOpenAI(api_key=get_api_key(args.provider))
    elif args.provider == "anthropic":
        client = AsyncAnthropic(api_key=get_api_key(args.provider))
    else:
        raise ValueError(f"Invalid provider: {args.provider}")
    out_path = Path(args.out_csv) if args.out_csv else None
    results = await run_elephant_base_experiment(
        df=df,
        client=client,
        out_path=out_path,
        model=args.model,
        max_tokens=args.max_tokens,
        max_concurrency=args.max_concurrency,
        run_binary=args.run_binary,
        overwrite=args.overwrite,
    )

    if out_path is None:
        print(results.to_csv(index=False), end="")
    else:
        print(f"Wrote {len(results)} rows to: {out_path}")
    
if __name__ == "__main__":
    asyncio.run(main())